/**
 * The generated campaign document (docs/SMS_TEMPLATES.md): every outbound text and automatic
 * reply, exactly as sent, with its length and segment cost. Generated from templates.ts so it
 * cannot drift; tests fail if the committed copy is stale. Regenerate with `npm run sms:templates`.
 */
import { ACCEPTED_SMS_CONSENT_LABELS, KEYWORDS, SMS_CONSENT_LABEL, allMessages, renderTemplate } from './templates.js';
import { smsInfo } from './smsEncoding.js';

// The phone is shown as a visible placeholder: the real number is the clinic's (CLINIC_PHONE), not a sample.
const SAMPLE = { first: 'Ingrid', day: 'Saturday, Oct 10', time: '9:00 AM', phone: '(XXX) XXX-XXXX' };
/** Longest realistic values: a 30-character first name, the longest weekday + month, the widest time. */
const WORST = { first: 'Wolfeschlegelsteinhausenberge', day: 'Wednesday, Sep 30', time: '12:45 PM', phone: '(XXX) XXX-XXXX' };

function fill(vars: string[], from: Record<string, string>): Record<string, string> {
  return Object.fromEntries(vars.map((v) => [v, from[v]!]));
}

export function renderTemplatesDoc(): string {
  const out: string[] = [];
  out.push('# Text messages — for the A2P campaign form');
  out.push('');
  out.push('> Generated by `npm run sms:templates` from `server/src/integrations/templates.ts`. **Do not edit by hand** —');
  out.push('> change the wording in that file and regenerate. A test fails if this copy is out of date.');
  out.push('');
  out.push('Every text may contain only the patient\'s **first name**, the appointment **day** and **time** — never a');
  out.push('service, provider, room or any clinical detail. Texts are sent only between 8:00 a.m. and 9:00 p.m. clinic time.');
  out.push('');
  out.push('## Opt-in');
  out.push('');
  out.push('A checkbox on the public booking page, **unchecked by default**, immediately above the "Request appointment" button:');
  out.push('');
  out.push(`> ☐ ${SMS_CONSENT_LABEL}`);
  out.push('');
  out.push('The time it was ticked and the exact words shown are stored with the booking. A front-desk team member can also');
  out.push('record consent given verbally or on paper on the patient\'s profile; how it was given is kept in the audit log.');
  if (ACCEPTED_SMS_CONSENT_LABELS.length > 1) out.push(`(${ACCEPTED_SMS_CONSENT_LABELS.length} wordings are currently accepted from open pages.)`);
  out.push('');
  out.push('## Keywords the system answers');
  out.push('');
  out.push('Matched against the whole message, ignoring case and surrounding punctuation.');
  out.push('');
  out.push('| Keyword | Action |');
  out.push('|---|---|');
  out.push(`| ${KEYWORDS.STOP.join(', ')} | Texts to that number stop; the patient is told once |`);
  out.push(`| ${KEYWORDS.START.join(', ')} | Texts may resume (consent already on file) |`);
  out.push(`| ${KEYWORDS.HELP.join(', ')} | Replies with the clinic's phone number |`);
  out.push(`| ${KEYWORDS.CONFIRM.join(', ')} | Marks the patient's next appointment as confirmed by them |`);
  out.push('');

  for (const [heading, kind] of [['Messages we send', 'outbound'], ['Automatic replies', 'reply']] as const) {
    out.push(`## ${heading}`);
    out.push('');
    for (const m of allMessages().filter((x) => x.kind === kind)) {
      const sample = renderTemplate(m.id, fill(m.variables, SAMPLE));
      const worst = renderTemplate(m.id, fill(m.variables, WORST));
      const si = smsInfo(sample);
      const wi = smsInfo(worst);
      out.push(`### \`${m.id}\``);
      out.push('');
      out.push(`**When:** ${m.when}`);
      out.push('');
      out.push('**Text (exactly as stored):**');
      out.push('');
      out.push(`    ${m.text}`);
      out.push('');
      out.push(`**Example:** ${sample}`);
      out.push('');
      out.push(`**Size:** ${si.length} characters · ${si.encoding} · ${si.segments} segment${si.segments === 1 ? '' : 's'}`
        + ` — longest realistic: ${wi.length} characters · ${wi.segments} segment${wi.segments === 1 ? '' : 's'}`);
      if (si.encoding === 'UCS-2') {
        out.push('');
        out.push(`> ⚠ Contains ${si.nonGsm.map((c) => `\`${c}\``).join(', ')}, which is not in the standard SMS (GSM-7) alphabet. That makes the **whole message`
          + ' Unicode**: 70 characters per segment instead of 160, so it costs more segments. Replacing it with a plain hyphen (`-`) keeps it GSM-7.');
      }
      out.push('');
    }
  }
  return out.join('\n').replace(/\n+$/, '\n');
}
